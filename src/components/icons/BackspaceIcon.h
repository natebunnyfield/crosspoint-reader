// Backspace key art at the resolutions the keyboard actually draws it.
//
// THE BUG THIS EXISTS FOR
//
// The SDK only ships lucideDeleteIcon16() — a 16x16 mask
// (FreeInkUICore.h:1443). keyboard.h sizes the delete glyph from the label
// font's advanceY and snaps it to a multiple of 16, which lands on 32 for all
// four System faces, then blits the 16px art into that 32px box with
// nearest-neighbour sampling (FreeInkUICore.h:365-380). So every device draws
// the backspace key at HALF the resolution of the text beside it: 2x2 blocks,
// a staircased arrow tip and an X whose diagonals do not join.
//
// BACKSPACE_32 is the same artwork at native 32px, so it blits 1:1 into that
// box. It is a 2x box-downsample of BACKSPACE_64 (ink where >= 2 of the 4
// source pixels are ink), which keeps it faithful to the art gen_icons.py
// produced from the SDK's own delete.svg rather than redrawing it by eye.
// rsvg-convert is not installed on every dev machine, so deriving it from the
// committed 64px art also means this header can be regenerated anywhere.
//
// Mask1 format throughout, matching the SDK: MSB-first, bit 0 = ink,
// bit 1 = transparent.
